"use strict";
const assert=require("node:assert/strict");
const {createGpuSampler,parseGpuCounters}=require("../desktop/gpu.cjs");
const a="pid_101_luid_0x00000000_0x00002020_phys_0_eng_0_engtype_3D";
const b="pid_202_luid_0x00000000_0x00002020_phys_0_eng_0_engtype_3D";
const copy="pid_909_luid_0x00000000_0x00002020_phys_0_eng_1_engtype_Copy";
const other="pid_501_luid_0x00000000_0x00009999_phys_0_eng_0_engtype_3D";
assert.equal(parseGpuCounters([{Name:a,UtilizationPercentage:28},{Name:b,UtilizationPercentage:17},{Name:copy,UtilizationPercentage:62},{Name:other,UtilizationPercentage:80}]),80,"Mais ocupado entre GPUs e motores");
assert.equal(parseGpuCounters([{Name:a,UtilizationPercentage:35},{Name:b,UtilizationPercentage:20},{Name:copy,UtilizationPercentage:10}]),55,"Agrupar processos no mesmo motor");
assert.equal(parseGpuCounters([{Name:a,UtilizationPercentage:88},{Name:b,UtilizationPercentage:78}]),100,"Não exceder 100%");
assert.equal(parseGpuCounters('[]'),null,"Sem amostras não significa GPU em 0%");
assert.equal(parseGpuCounters('bad json'),null);
assert.equal(parseGpuCounters([{Name:a,UtilizationPercentage:"NaN"}]),null);
assert.equal(parseGpuCounters([{Name:"Total",UtilizationPercentage:44}]),null,"Não inventar identidade de motor");
(async()=>{
 let now=1000,calls=0,complete;
 const execFileFn=(exe,args,options,callback)=>{
   calls++;complete=callback;
   assert.equal(exe,"powershell.exe");
   assert.ok(args.includes("-NonInteractive"));
   assert.ok(args.includes("-NoProfile"));
   assert.ok(args[args.length-1].includes("Win32_PerfFormattedData_GPUPerformanceCounters_GPUEngine"));
   assert.ok(options.windowsHide);assert.ok(options.timeout<=5000);
 };
 const probe=createGpuSampler({platform:"win32",execFileFn,clock:()=>now,intervalMs:50000});
 assert.equal(probe.sample().percent,null,"Início sem valor falso");
 probe.start();assert.equal(calls,1);
 probe.refresh();assert.equal(calls,1,"Não iniciar concorrência entre sondagens");
 complete(null,JSON.stringify([{Name:a,UtilizationPercentage:23},{Name:b,UtilizationPercentage:35}]),"");
 assert.equal(probe.sample().percent,58);
 assert.equal(probe.sample().status,"ready");
 now+=14000;assert.equal(probe.sample().status,"stale");
 assert.equal(probe.sample().percent,null,"Leitura antiga não é leitura atual");
 probe.refresh();assert.equal(calls,2);
 complete(new Error("Counters unavailable"),"", "");
 assert.equal(probe.sample().status,"unavailable");
 assert.equal(probe.sample().percent,null);
 probe.stop();
 const linux=createGpuSampler({platform:"linux",execFileFn:()=>{throw Error("não deveria executar");}});
 linux.start();linux.refresh();
 assert.equal(linux.sample().status,"unsupported");
 console.log("[PC Monitor] GPU WDDM agrupada, ausência e timeout, sem GPU inventada: OK");
})().catch(err=>{console.error(err);process.exitCode=1;});
