batch.rows.push({id:"row-2",quantity:3,values:{[batch.fields[0]]:"Café",[batch.fields[1]]:"R$ 22,90"}});
assert.equal(B.count(batch),25);
let result=B.pages(template,batch);
assert.equal(result.pages.length,2);
assert.equal(result.pages[0].length,18);
assert.equal(result.pages[1].length,7);
assert.equal(result.pages[0][0].label.objects.find(o=>(o.binding||o.id)===batch.fields[0]).text,"Biscoito integral");
assert.equal(result.pages[1][4].label.objects.find(o=>(o.binding||o.id)===batch.fields[0]).text,"Café");
assert.equal(template.objects.find(o=>(o.binding||o.id)===batch.fields[0]).text,"NOME DO PRODUTO","Modelo original não pode ser alterado pela lista");
batch.layout={...batch.layout,columns:2,rows:4,gapX:4,gapY:3,alignX:"end",alignY:"center"};
