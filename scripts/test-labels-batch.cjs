"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path");
const root=path.resolve(__dirname,"..");
const M=require("../apps/estoque/etiquetas/model.js");
const B=require("../apps/estoque/etiquetas/lote/batch-model.js");
const template=M.project("preco");
const batch=B.fresh(template);
const defs=B.variableFields(template);
assert.equal(defs.length,3,"Modelo preço tem três campos de texto");
assert.equal(batch.fields.length,2,"Primeiros dois campos iniciam como variáveis");
assert.equal(batch.rows.length,1);
