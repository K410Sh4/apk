assert.equal(layout.perPage,8);assert.equal(layout.positions[0].x,81);
assert.equal(layout.positions[1].x,145);
assert.equal(layout.positions[0].y,64);
result=B.pages(template,batch);assert.equal(result.pages.length,4);
for(const p of result.pages.flat())assert.ok(p.position.x>=0&&p.position.y>=0&&p.position.x+60<=210&&p.position.y+40<=297);
assert.throws(()=>B.calculate(template,{...batch.layout,columns:4}),/excede/);
assert.throws(()=>B.calculate(template,{...batch.layout,rows:10}),/excede/);
batch.layout={...batch.layout,columns:"auto",rows:"auto",alignX:"center",alignY:"start"};
batch.rows[0].quantity=200;batch.rows[1].quantity=200;result=B.pages(template,batch);
assert.equal(result.copies,400);assert.equal(result.pages.length,Math.ceil(400/18));
batch.rows.push({id:"row-3",quantity:101,values:{}});assert.throws(()=>B.pages(template,batch),/500/);
const barcode=M.project("codigo"),barcodeData=B.fresh(barcode);
const bfield=B.variableFields(barcode).find(x=>x.type==="barcode");
assert.ok(bfield);
barcodeData.fields=[bfield.id];
barcodeData.rows[0].values[bfield.id]="INVALID_ABC";
assert.throws(()=>B.pages(barcode,barcodeData),/Code 39/);
barcodeData.rows[0].values[bfield.id]="EST-001";
assert.equal(B.pages(barcode,barcodeData).copies,1);
